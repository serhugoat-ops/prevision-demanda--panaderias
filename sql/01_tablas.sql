-- Histórico de ventas anterior a la web (importado desde Excel/CSV).
-- Permite que el modelo arranque con meses de datos desde el primer día
-- en lugar de esperar a que los panaderos acumulen registros.
CREATE TABLE IF NOT EXISTS ventas_historicas (
    id          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  text    NOT NULL,
    fecha       date    NOT NULL,
    producto_id text    NOT NULL,
    producido   integer NOT NULL DEFAULT 0 CHECK (producido >= 0),
    merma       integer NOT NULL DEFAULT 0 CHECK (merma >= 0),
    FOREIGN KEY (cliente_id, producto_id) REFERENCES productos (cliente_id, producto_id)
);

CREATE INDEX IF NOT EXISTS ventas_historicas_cliente_fecha_idx
    ON ventas_historicas (cliente_id, fecha);

-- Calendario de festivos. Un festivo se comporta como un domingo
-- (afluencia y mix de producto parecidos), así que el modelo lo agrupa
-- con los domingos en vez de mezclarlo con su día laborable.
-- Mantenimiento: subir las 10-12 fechas del año nuevo cada enero.
CREATE TABLE IF NOT EXISTS dias_festivos (
    fecha  date PRIMARY KEY,
    nombre text NOT NULL
);

-- Salida del modelo: cuántas unidades hornear de cada producto en los
-- próximos 7 días. Es lo que la web enseña al panadero cada mañana.
CREATE TABLE IF NOT EXISTS produccion_recomendada (
    cliente_id           text    NOT NULL,
    fecha                date    NOT NULL,
    producto_id          text    NOT NULL,
    cantidad_recomendada integer NOT NULL CHECK (cantidad_recomendada >= 0),
    generado_en          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (cliente_id, fecha, producto_id),
    FOREIGN KEY (cliente_id, producto_id) REFERENCES productos (cliente_id, producto_id)
);
